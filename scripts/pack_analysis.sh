#!/bin/bash
# Pack the analyses under artifacts/ into one tar.gz for download.
# Model weights, tokenizers and the Base checkpoint are always left out. backups/ is
# kept: its zip is the only remaining copy of experiment 03's reports.
#
# Levels (raw size before compression):
#   essential (default)  reports (*.md), plots, scores (csv/json), training logs and
#                        curves, generated SAMSum responses. Drops the raw per-token,
#                        per-sample and per-example dumps.                     (~125 MB)
#   --light              essential + lm-eval *.samples.jsonl and BoolQ *.examples.jsonl
#                                                                              (~0.5 GB)
#   --full               everything except weights, incl. *.tokens.jsonl      (~1.9 GB)
#
# --clean (combine with any level) drops every per-model file of the pure-bf16
# Full SFT / Steer-Full / FAPM checkpoints (first run and experiment 04), whose
# weights barely moved; see docs/experiments/05. Tables that mix them with the
# clean models stay in, and CLEAN_NOTES.md in the archive lists them.
#
# Usage:
#   bash scripts/pack_analysis.sh [--light|--full] [--clean]
#   OUT_DIR=/some/dir bash scripts/pack_analysis.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="${OUT_DIR:-$ROOT}"
LEVEL=essential
CLEAN=0
for arg in "$@"; do
  case "$arg" in
    --essential|--light|--full) LEVEL="${arg#--}" ;;
    --clean) CLEAN=1 ;;
    *) echo "Unknown option '$arg' (use --light, --full, --clean)" >&2; exit 1 ;;
  esac
done

excludes=(
  --exclude='./base'
  --exclude='*.safetensors'
  --exclude='tokenizer.json' --exclude='vocab.json' --exclude='merges.txt'
  --exclude='*.pid'
  --exclude='__pycache__'
)
case "$LEVEL" in
  essential)
    excludes+=(
      --exclude='*.tokens.jsonl'
      --exclude='*.samples.jsonl'
      --exclude='*.examples.jsonl'
      --exclude='boolq.validation.jsonl'  # input data, regenerated by the margin scripts
    ) ;;
  light) excludes+=(--exclude='*.tokens.jsonl') ;;
esac

extra=()
name="$LEVEL"
if (( CLEAN )); then
  name="$LEVEL-clean"
  for run in fair-methods-2epoch-log25-tmux update-directions-existing-20261003; do
    for m in full_sft steer_full fapm; do
      excludes+=(--exclude="./samsum/$run/*$m*")
    done
  done
  notes_dir="$(mktemp -d)"
  trap 'rm -rf "$notes_dir"' EXIT
  cat > "$notes_dir/CLEAN_NOTES.md" <<'EOF'
# Bản lọc: bỏ checkpoint bf16 thuần

Full SFT, Steer-Full và FAPM của lượt đầu (`samsum/fair-methods-2epoch-log25-tmux/`) train với weight bf16 thuần,
nên update AdamW bị làm tròn mất (chỉ 11,5% tham số đổi; FAPM ≈ Base). Mọi file riêng của ba model này đã bị loại,
kể cả trong `samsum/update-directions-existing-20261003/`.

Còn giữ và dùng được:
- `samsum/fp32-master-2epoch-20261012/`: toàn bộ (weight fp32, tính bf16 autocast).
- `samsum/fixed-margin-causal-128step-20261003/`: toàn bộ (6 arm LoRA, adapter fp32).
- `samsum/fair-methods-2epoch-log25-tmux/`: Base, LoRA, Steer-LoRA.
- `samsum/update-directions-existing-20261003/`: phần LoRA, Steer-LoRA.
- `backups/*.zip`: chỉ lấy `steer-base-anchor-2epoch-lambda1-20261003/` (thí nghiệm 03, Steer-LoRA + neo Base).
  Zip là bản sao ngày 2026-10-04 chưa lọc, phần còn lại có cả model bf16.

Các file tổng hợp sau vẫn có dòng/cột của ba model bf16. Bỏ qua `full_sft`, `steer_full`, `fapm`
(và "Full SFT", "Steer-Full", "FAPM") khi đọc:
- `samsum/fair-methods-2epoch-log25-tmux/`: **mọi file tổng hợp còn lại** — `REPORT.md`, `stable-five*/`
  (`results.md`, `scores.csv`, `summary.json`, hình), toàn bộ `reports/` (`margin-mechanism/`, `distribution-comparison*/`,
  `margin-audit-*/`, `gpu-actual-gradients-*/`, `kl/summary.json`, `fairness_manifest.json`), `logs/`.
- `samsum/update-directions-existing-20261003/`: **mọi file tổng hợp còn lại** — `ANALYSIS_VI.md`, `RUN_SETUP.md`,
  `part1/`, `part2a/` (`BATCH_ANALYSIS.*`, `REPORT.md`, `results.json`, `run_manifest.json`), `direction_summary.*`,
  `RESULT_VALIDATION.json`, `BUDGET_*.json`, `logs/`.
- `samsum/fixed-margin-causal-128step-20261003/REPORT.md`: bảng tham chiếu cuối file chép điểm của lượt đầu, gồm
  ba dòng bf16. Các arm của thí nghiệm này (ce, steer, ...) đều sạch.
- `samsum/fp32-master-2epoch-20261012/scores-bf16-vs-fp32.png`: cố ý so bản bf16 với fp32.
- `samsum/fp32-master-2epoch-20261012/*-alpha*/summary.json`: trường `models` là bảng tra đường dẫn mặc định có trỏ
  tới thư mục bf16, nhưng model thực sự chấm là `alpha*` (dựng từ Full SFT fp32); điểm số sạch.
EOF
  extra=(-C "$notes_dir" CLEAN_NOTES.md)
fi

mkdir -p "$OUT_DIR"
out="$OUT_DIR/sdft-analysis-$(date +%Y%m%d-%H%M)-$name.tar.gz"
tar "${excludes[@]}" -czf "$out" -C "$ROOT/artifacts" . "${extra[@]}"
echo "Wrote $out ($(du -h "$out" | cut -f1), $(tar -tzf "$out" | grep -vc '/$') files)"
